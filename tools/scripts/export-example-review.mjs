// Copies real reviews and one real bench result into the web app as the examples the marketing
// page shows. Every file is checked against its schema first, so a broken one is never shipped.
//
//   node tools/scripts/export-example-review.mjs --runs-dir <dir> --good <run-id> --risky <run-id> \
//     --suite <suite.json> --result <result.json>
//
// The bench result's test output is dropped (it is long and the page does not show it).
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { workspaceRoot } from './run-command.mjs';

const { values } = parseArgs({
  options: {
    'runs-dir': { type: 'string' },
    good: { type: 'string' },
    risky: { type: 'string' },
    suite: { type: 'string' },
    result: { type: 'string' },
  },
});
for (const key of ['good', 'risky', 'suite', 'result']) {
  if (!values[key]) {
    console.error(
      'Usage: node tools/scripts/export-example-review.mjs --runs-dir <dir> --good <run-id> --risky <run-id> --suite <suite.json> --result <result.json>',
    );
    process.exit(2);
  }
}

const contracts = await import('../../packages/contracts/dist/index.js');
const runsDir = resolve(values['runs-dir'] ?? join(workspaceRoot, '.avero', 'runs'));

async function review(runId) {
  if (!/^[A-Za-z0-9_-]{1,128}$/.test(runId)) throw new Error(`Bad run id ${runId}`);
  const record = contracts.parseRunRecord(await readFile(join(runsDir, `${runId}.jsonl`), 'utf8'));
  const verdict = contracts.verdictSchema.parse(
    JSON.parse(await readFile(join(runsDir, `${runId}.verdict.json`), 'utf8')),
  );
  const summary = contracts.summarizeRun(record);
  return {
    task: record.started.task,
    status: summary.status,
    durationMs: summary.durationMs,
    filesChanged: summary.filesChanged,
    additions: summary.additions,
    deletions: summary.deletions,
    verdict,
  };
}

const suite = contracts.benchSuiteSchema.parse(
  JSON.parse(await readFile(resolve(values.suite), 'utf8')),
);
const result = contracts.benchResultSchema.parse(
  JSON.parse(await readFile(resolve(values.result), 'utf8')),
);
const ran = new Set(result.cells.map((cell) => cell.taskId));
const bench = {
  tasks: suite.tasks
    .filter((task) => ran.has(task.id))
    .map((task) => ({ id: task.id, title: task.title })),
  result: {
    ...result,
    cells: result.cells.map((cell) => ({ ...cell, testsOutput: '' })),
    configs: result.configs.map((config) => ({
      ...config,
      rules: config.rules.map((file) => ({ path: file.path, content: file.content })),
    })),
  },
};
contracts.benchResultSchema.parse(bench.result);

const data = { good: await review(values.good), risky: await review(values.risky), bench };
const target = join(workspaceRoot, 'apps', 'web', 'src', 'content', 'example-review.ts');
await mkdir(dirname(target), { recursive: true });
await writeFile(
  target,
  `// Generated by tools/scripts/export-example-review.mjs. Do not edit by hand.\n` +
    `// Real reviews of real recorded runs, and one real bench result (4 attempts).\n` +
    `export const exampleReviewJson = ${JSON.stringify(JSON.stringify(data))};\n`,
);
console.log(`Wrote ${target}.`);

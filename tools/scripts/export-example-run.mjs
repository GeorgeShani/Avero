// Copies one recorded run into the web app as the example the marketing page replays.
//   node tools/scripts/export-example-run.mjs <run-id> [runs-dir]
// The record is checked against the run-record schema first, so a broken file is never shipped.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { workspaceRoot } from './run-command.mjs';

const [runId, runsDirArg] = process.argv.slice(2);
if (!runId || !/^[A-Za-z0-9_-]{1,128}$/.test(runId)) {
  console.error('Usage: node tools/scripts/export-example-run.mjs <run-id> [runs-dir]');
  process.exit(2);
}

const { parseRunRecord } = await import('../../packages/contracts/dist/index.js');
const runsDir = resolve(runsDirArg ?? join(workspaceRoot, '.avero', 'runs'));
const text = await readFile(join(runsDir, `${runId}.jsonl`), 'utf8');
const record = parseRunRecord(text);
if (!record.finished) {
  console.error('That run has not finished. Export a finished run.');
  process.exit(1);
}

const target = join(workspaceRoot, 'apps', 'web', 'src', 'content', 'example-run.ts');
await mkdir(dirname(target), { recursive: true });
await writeFile(
  target,
  `// Generated by tools/scripts/export-example-run.mjs from run ${runId}. Do not edit by hand.\n` +
    `// A real recorded run (the recorder scrubs secrets and the workspace path before it is saved).\n` +
    `export const exampleRunJsonl = ${JSON.stringify(text)};\n`,
);
console.log(`Wrote ${target} (${text.length} characters, ${record.events.length} events).`);
